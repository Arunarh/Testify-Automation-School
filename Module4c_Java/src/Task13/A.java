package Task13;

public class A {

    // Constructor 1
    public A() {
        System.out.println("Constructor 1: No information provided.");
    }

    // Constructor 2
    public A(String name) {
        System.out.println("Constructor 2: My name is " + name);
    }

    // Constructor 3
    public A(String name, int age) {
        System.out.println("Constructor 3: My name is " + name + " and I am " + age + " years old.");
    }
}